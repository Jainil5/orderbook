/**
 * AI provider contract — SERVER ONLY.
 *
 * Contract this file defines and everything else must respect:
 *
 * - Environment names read: `ORDERBOOK_AI_API_KEY` (secret),
 *   `ORDERBOOK_AI_BASE_URL` (optional endpoint override), `ORDERBOOK_AI_MODEL`
 *   (optional model id). All three are plain server env vars in `.env.local` /
 *   Railway. None may be prefixed `NEXT_PUBLIC_`: a `NEXT_PUBLIC_*` value is
 *   inlined into the browser bundle at build time, so a model key published
 *   that way is public.
 * - Only `status`, `label`, `model` (the model *id*, not a secret), `envNames`
 *   and `missing` are ever returned. Key and base-URL values are never read
 *   into a returned object, logged, or passed to a client component.
 * - Importers: server modules and server actions only (`lib/ai/loader.ts`,
 *   `services/ai-actions.ts`). The `window` guard below is a backstop, not the
 *   boundary — the boundary is that no client component may import this file.
 * - `status: "configured"` means credentials are present. It does **not** mean
 *   text is generated by a model: this build ships no request client, so
 *   `supportsTextGeneration` stays false and every answer in `/ai` keeps
 *   reporting the local insight engine as its source. Wiring a real adapter
 *   means implementing a fetch against `ORDERBOOK_AI_BASE_URL` here, server
 *   side, and only then flipping that flag.
 */

import type { AiProviderState } from "./types";

export const AI_ENV_NAMES = [
  "ORDERBOOK_AI_API_KEY",
  "ORDERBOOK_AI_BASE_URL",
  "ORDERBOOK_AI_MODEL",
] as const;

const API_KEY_ENV = "ORDERBOOK_AI_API_KEY";
const BASE_URL_ENV = "ORDERBOOK_AI_BASE_URL";
const MODEL_ENV = "ORDERBOOK_AI_MODEL";

/** No request client exists in this build; see the header comment. */
export const SUPPORTS_TEXT_GENERATION = false;

const PLACEHOLDER = /placeholder|changeme|your_|xxx/i;

function readEnv(name: string): string {
  // `process.env` does not exist in a browser bundle. Reaching this file from a
  // client component is a bug, so fail loudly instead of returning a guess.
  if (typeof window !== "undefined") {
    throw new Error("getAiProvider is server-only and cannot run in the browser.");
  }
  return process.env[name]?.trim() ?? "";
}

export type AiProviderInfo = AiProviderState & {
  /** True only when a model could actually be called. Always false today. */
  supportsTextGeneration: boolean;
};

/**
 * Reports what is configured without exposing what is configured *with*.
 * Safe to render.
 */
export function getAiProvider(): AiProviderInfo {
  const apiKey = readEnv(API_KEY_ENV);
  const baseUrl = readEnv(BASE_URL_ENV);
  const model = readEnv(MODEL_ENV);

  const missing: string[] = [];
  if (!apiKey || PLACEHOLDER.test(apiKey)) missing.push(API_KEY_ENV);
  if (!baseUrl) missing.push(BASE_URL_ENV);

  if (missing.length > 0) {
    return {
      status: "not_configured",
      label: "Local insight engine — no model configured",
      model: model || null,
      envNames: AI_ENV_NAMES,
      missing,
      supportsTextGeneration: false,
    };
  }

  return {
    status: "configured",
    label:
      "Model credentials present, but this build has no request client — answers still come from the local insight engine",
    model: model || null,
    envNames: AI_ENV_NAMES,
    missing: [],
    supportsTextGeneration: SUPPORTS_TEXT_GENERATION,
  };
}
