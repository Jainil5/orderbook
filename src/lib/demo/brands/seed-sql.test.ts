import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";
import { buildOrderHistory } from "./history";
import {
  BREWERY_CAFE_DEMO,
  BREWERY_CAFE_HISTORY_CFG,
} from "./brewery-cafe";
import {
  CUBIG_FURNITURE_DEMO,
  CUBIG_FURNITURE_HISTORY_CFG,
} from "./cubig-furniture";
import type { DemoBrandPack } from "./types";
import type { Customer, Order, OrderItem, Payment } from "@/types/database";

// A fixed clock keeps the generated SQL byte-stable across days — the seed is a
// snapshot, not a live view. Nov 10 mirrors the program's real "today" and the
// invariant clock used by history.test.ts.
const NOW = new Date(2026, 10, 10, 21, 30, 0);

// Only the columns the live Supabase path actually reads (see
// src/services/data.ts selects). The lifecycle-new columns (order_type,
// service_date, payment_method, guests, delivery_address, payment_reference,
// offer_code_snapshot) exist in the app model but are left out here pending the
// Plan B schema audit — extend this file if your live schema carries them.
const ORDER_COLS = [
  "id",
  "brand_id",
  "order_number",
  "status",
  "payment_status",
  "customer_id",
  "customer_name_snapshot",
  "subtotal",
  "discount_total",
  "tax_total",
  "fees_total",
  "grand_total",
  "notes",
  "created_at",
  "amount_paid",
  "order_kind",
] as const;
const ITEM_COLS = [
  "id",
  "order_id",
  "product_id",
  "product_name_snapshot",
  "quantity",
  "unit_price",
  "line_discount",
  "line_total",
] as const;
const PAYMENT_COLS = [
  "id",
  "brand_id",
  "order_id",
  "amount",
  "method",
  "status",
  "created_at",
] as const;
const CUSTOMER_COLS = [
  "id",
  "brand_id",
  "name",
  "email",
  "phone",
  "notes",
] as const;

function sqlValue(value: unknown): string {
  if (value === null || value === undefined) return "NULL";
  if (typeof value === "number") return String(value);
  if (typeof value === "boolean") return value ? "true" : "false";
  return `'${String(value).replace(/'/g, "''")}'`;
}

function tuple(row: Record<string, unknown>, cols: readonly string[]): string {
  return `(${cols.map((c) => sqlValue(row[c])).join(", ")})`;
}

function insertStatement<T extends object>(
  table: string,
  cols: readonly string[],
  rows: T[],
): string {
  if (rows.length === 0) return "";
  const values = rows
    .map((r) => tuple(r as Record<string, unknown>, cols))
    .join(",\n  ");
  return `INSERT INTO ${table} (${cols.join(", ")}) VALUES\n  ${values}\nON CONFLICT (id) DO NOTHING;`;
}

/** Hand fixtures (base pack rows) + deterministic history, per brand. */
function collectRows(pack: DemoBrandPack, cfg: typeof BREWERY_CAFE_HISTORY_CFG) {
  const history = buildOrderHistory(cfg, NOW);
  const isHistory = (id: string, prefix: string) => id.startsWith(prefix);
  const customers: Customer[] = [
    ...pack.customers.filter((c) => !isHistory(c.id, "h-cust-")),
    ...history.customers,
  ];
  const orders: Order[] = [
    ...pack.orders.filter((o) => !isHistory(o.id, "hist-")),
    ...history.orders,
  ];
  const orderItems: OrderItem[] = [
    ...pack.orderItems.filter((i) => !isHistory(i.id, "hist-")),
    ...history.orderItems,
  ];
  const payments: Payment[] = [
    ...pack.payments.filter((p) => !isHistory(p.id, "hist-pay-")),
    ...history.payments,
  ];
  return { customers, orders, orderItems, payments };
}

/** Single source of truth for both the dump and the verification counts. */
function assembleDataset() {
  const br1 = collectRows(BREWERY_CAFE_DEMO, BREWERY_CAFE_HISTORY_CFG);
  const br2 = collectRows(CUBIG_FURNITURE_DEMO, CUBIG_FURNITURE_HISTORY_CFG);
  return {
    customers: [...br1.customers, ...br2.customers],
    orders: [...br1.orders, ...br2.orders],
    orderItems: [...br1.orderItems, ...br2.orderItems],
    payments: [...br1.payments, ...br2.payments],
  };
}

function buildSql(): string {
  const { customers, orders, orderItems, payments } = assembleDataset();

  const header = `-- OrderBook demo history — paste-ready Supabase seed
--
-- Generated by src/lib/demo/brands/seed-sql.test.ts (DUMP_SEED_SQL=1 npx vitest run src/lib/demo/brands/seed-sql.test.ts).
-- Deterministic: the 6-month history comes from buildOrderHistory() at a fixed
-- clock (2026-11-09 seed, "now" = 2026-10 Nov 2026), so re-running reproduces these rows.
--
-- TARGET: run against your live Supabase project (SQL editor or psql).
--   * brand_id values are the DEMO pack ids (demo-brewery-cafe / demo-cubig-furniture).
--     Replace them with your real brand uuid(s), or create those brand rows first.
--   * id columns are the app's string ids (hist-*, h-cust-*, o1, …). If your schema
--     requires uuid, remap before pasting. The Plan B schema audit covers this drift.
--   * Newer lifecycle columns (order_type, service_date, payment_method, guests,
--     delivery_address, payment_reference, offer_code_snapshot) are intentionally
--     omitted; add them to the column lists if your live schema has them.
-- Idempotent: every insert uses ON CONFLICT (id) DO NOTHING, so re-pasting is safe.
-- Parents precede children: customers → orders → order_items → payments.

BEGIN;

-- ${customers.length} customers, ${orders.length} orders, ${orderItems.length} order items, ${payments.length} payments`;

  const body = [
    insertStatement("customers", CUSTOMER_COLS, customers),
    insertStatement("orders", ORDER_COLS, orders),
    insertStatement("order_items", ITEM_COLS, orderItems),
    insertStatement("payments", PAYMENT_COLS, payments),
  ]
    .filter(Boolean)
    .join("\n\n");

  return `${header}\n\n${body}\n\nCOMMIT;\n`;
}

function countValueRows(sql: string, table: string): number {
  const start = sql.indexOf(`INSERT INTO ${table} `);
  if (start === -1) return 0;
  const valuesIdx = sql.indexOf(" VALUES", start);
  const onConflict = sql.indexOf("\nON CONFLICT", valuesIdx);
  const block = sql.slice(valuesIdx, onConflict);
  return (block.match(/\n  \(/g) || []).length;
}

const OUT_FILE = fileURLToPath(
  new URL("../../../../docs/SUPABASE_SEED_HISTORY.sql", import.meta.url),
);

describe("Supabase seed SQL export", () => {
  it("writes docs/SUPABASE_SEED_HISTORY.sql when DUMP_SEED_SQL=1", () => {
    if (process.env.DUMP_SEED_SQL !== "1") return;
    writeFileSync(OUT_FILE, buildSql(), "utf8");
    expect(existsSync(OUT_FILE)).toBe(true);
  });

  it("exists, is substantial, and is internally consistent", () => {
    if (process.env.DUMP_SEED_SQL === "1") return;
    expect(existsSync(OUT_FILE)).toBe(true);
    const sql = readFileSync(OUT_FILE, "utf8");
    expect(sql.length).toBeGreaterThan(100_000);
    expect(sql.startsWith("--")).toBe(true);
    expect(sql).toContain("INSERT INTO orders");
    expect(sql).toContain("INSERT INTO customers");
    expect(sql).toContain("INSERT INTO order_items");
    expect(sql).toContain("INSERT INTO payments");
    expect(sql.trimEnd().endsWith("COMMIT;")).toBe(true);

    // Integrity: the value rows in each statement must match a freshly
    // assembled (fixed-clock) dataset — catches truncation or column drift.
    const data = assembleDataset();
    expect(countValueRows(sql, "customers")).toBe(data.customers.length);
    expect(countValueRows(sql, "orders")).toBe(data.orders.length);
    expect(countValueRows(sql, "order_items")).toBe(data.orderItems.length);
    expect(countValueRows(sql, "payments")).toBe(data.payments.length);
  });

  it("every order statement keeps the exact column arity", () => {
    if (process.env.DUMP_SEED_SQL === "1") return;
    const sql = readFileSync(OUT_FILE, "utf8");
    const ordersBlock = /INSERT INTO orders \(([^)]*)\) VALUES/.exec(sql);
    expect(ordersBlock).not.toBeNull();
    expect(ordersBlock![1].split(",").length).toBe(ORDER_COLS.length);
  });
});
